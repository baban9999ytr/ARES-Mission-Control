export function applyStaticTranslations(root=document){
  document.documentElement.lang=current;
  document.title=t(document.querySelector('.sources-page')?'sources.title':'app.title');
  for(const el of root.querySelectorAll('[data-i18n]'))el.textContent=t(el.dataset.i18n);
  for(const [selector,key,kind] of bindings){const el=root.querySelector(selector);if(!el)continue;
    if(kind==='firstText'){const node=[...el.childNodes].find(n=>n.nodeType===Node.TEXT_NODE&&n.textContent.trim());if(node)node.textContent=t(key)+' ';}
    else if(kind==='lastText'){const node=[...el.childNodes].reverse().find(n=>n.nodeType===Node.TEXT_NODE&&n.textContent.trim());if(node)node.textContent=' '+t(key);}
    else if(kind==='parentLastText'){const node=[...el.parentNode.childNodes].reverse().find(n=>n.nodeType===Node.TEXT_NODE&&n.textContent.trim());if(node)node.textContent=' '+t(key);}
    else if(el.children.length===0)el.textContent=t(key);
  }
  for(const [selector,attribute,key] of attributes){const el=root.querySelector(selector);if(el)el.setAttribute(attribute,t(key));}
  const sourceBrand=root.querySelector('.sources-page .brand');if(sourceBrand)sourceBrand.setAttribute('aria-label',t('sources.brandLabel'));
  for(const group of root.querySelectorAll('.language-switch'))group.setAttribute('aria-label',t('sources.languageLabel'));
  document.querySelectorAll('[data-language]').forEach(button=>button.setAttribute('aria-pressed',String(button.dataset.language===current)));
}
export function setLanguage(next){if(next!=='en'&&next!=='tr')return;current=next;try{localStorage.setItem('ares-language',next);}catch{}applyStaticTranslations();}
